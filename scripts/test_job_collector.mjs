import assert from 'node:assert/strict';
import {checkpoint,ensureResume,checkPage,companyLink,addJob,canonicalJob,validateConfig} from './job_collector_core.mjs';
const c={city:'101210100',queries:['示例'],targetCompanies:100,maxJobDetails:200,delayMs:1500};
const s=checkpoint(c),job={url:'https://www.zhipin.com/job_detail/sample.html?track=x',text:'职位描述',companyLinks:[]};
assert.equal(canonicalJob(job.url),'https://www.zhipin.com/job_detail/sample.html');
assert.throws(()=>canonicalJob('https://example.invalid/job_detail/sample.html'));
assert.throws(()=>validateConfig({...c,delayMs:1}));
assert.throws(()=>ensureResume(s,{...c,queries:['changed']}));
assert.throws(()=>checkPage({text:'请完成验证'}),/STOP/);
assert.throws(()=>checkPage({text:'登录查看完整内容'}),/STOP/);
assert.equal(companyLink({...job,links:[{href:'https://www.zhipin.com/gongsi/recommend.html',text:'推荐公司'}]}),null);
const cl={href:'https://www.zhipin.com/gongsi/sample.html',text:'示例主体'};
assert.equal(companyLink({...job,companyLinks:[cl,{...cl,href:'https://www.zhipin.com/gongsi/other.html'}]}),null);
addJob(s,job);assert.equal(s.companies.length,0);assert.equal(s.jobs[0].companyKey,null);
assert.equal(addJob(s,job),false);
const company={url:cl.href,text:'工商信息'};
addJob(s,{...job,url:'https://www.zhipin.com/job_detail/second.html',companyLinks:[cl]},company);
addJob(s,{...job,url:'https://www.zhipin.com/job_detail/third.html',companyLinks:[cl]},company);
assert.equal(s.jobs.length,3);assert.equal(s.companies.length,1);assert.equal(s.review,'pending');
console.log('PASS collector pure-policy checks: limits, config identity, URL scope, stop rules, anonymous isolation, multi-job company dedupe. Live CDP/DOM not verified.');
